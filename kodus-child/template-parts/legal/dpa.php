<h1>Data Processing Agreement (DPA)</h1>

<p><strong>Last Updated:</strong> November 2026</p>

<p>This DPA forms part of the <a href="https://kodus.io/en/terms-of-use/">Kodus Terms of Use</a> and applies automatically when you use the Services. No signature is required.</p>

<p><strong>Parties:</strong></p>
<ul>
  <li><strong>Processor:</strong> Kodus LLC, a company organized under the laws of the State of Delaware, United States of America, with registered address at 1007 N Orange St, 4th Floor, 1139, Wilmington, DE 19801 ("Processor").</li>
  <li><strong>Controller:</strong> The customer identified in the applicable main services agreement or order form ("Controller").</li>
</ul>

<h4>1. Subject Matter &amp; Duration</h4>
<p>1.1 This Data Processing Agreement ("DPA") governs the Processing of Personal Data by Processor on behalf of Controller in connection with Controller’s use of Processor’s AI code review and related services (the "Services").</p>
<p>1.2 The duration of this DPA is the same as the term of the underlying services agreement between the Parties ("Agreement"), unless otherwise required by applicable law.</p>

<h4>2. Roles of the Parties</h4>
<p>2.1 Controller is the "controller" and Processor is the "processor" as defined in GDPR and the equivalent concepts under the LGPD and other applicable data protection laws.</p>
<p>2.2 Controller determines the purposes and means of Processing of Personal Data. Processor will Process Personal Data only on documented instructions from Controller, as set out in this DPA, the Agreement, or as otherwise documented by Controller.</p>

<h4>3. Type of Personal Data &amp; Categories of Data Subjects</h4>
<p>3.1 The Personal Data Processed by Processor typically includes, but is not limited to:</p>
<ul>
  <li>Identification data (e.g. name, username, email address, organization, role).</li>
  <li>Technical data (e.g. IP address, device information, log data, usage metadata).</li>
  <li>Account and workspace configuration data.</li>
  <li>Communications and notification preferences.</li>
</ul>
<p>3.2 In the context of the Services, Controller may also submit or make available source code and associated metadata that can contain Personal Data (for example, commit metadata, author names, emails, comments, issue descriptions).</p>
<p>3.3 The categories of Data Subjects may include:</p>
<ul>
  <li>Controller’s employees, contractors, and users.</li>
  <li>Other individuals whose Personal Data appears in source code, comments, tickets, or other artifacts provided by Controller.</li>
</ul>
<p>3.4 The Parties agree that the Services are not intended for the Processing of special categories of Personal Data or data relating to children, and Controller will not intentionally submit such data to the Services.</p>

<h4>4. Nature &amp; Purpose of Processing</h4>
<p>4.1 Processor will Process Personal Data solely for the following purposes:</p>
<ul>
  <li>To provide, operate, and maintain the Services.</li>
  <li>To perform automated and assisted code review, including generating suggestions, comments, and analysis based on code, configuration, and related metadata.</li>
  <li>To provide support, troubleshooting, and incident response.</li>
  <li>To maintain security, prevent abuse, perform logging, auditing, monitoring, and fraud prevention.</li>
  <li>To generate aggregated or anonymized statistics to improve the Services, provided such output does not identify Controller or Data Subjects.</li>
</ul>
<p>4.2 Processor will not:</p>
<ul>
  <li>Sell Personal Data.</li>
  <li>Use Personal Data for advertising or profiling unrelated to the Services.</li>
  <li>Use Controller’s Personal Data or customer code to train or fine-tune any foundation model (including models provided by Anthropic, OpenAI, Novita or others), except where Controller has expressly enabled such feature in writing or via the Services.</li>
  <li>Process Personal Data in a way that is incompatible with Controller’s documented instructions or applicable laws.</li>
</ul>

<h4>5. Documented Instructions</h4>
<p>5.1 Processor will Process Personal Data only on documented instructions from Controller, including with respect to transfers of Personal Data to a third country or international organization, unless required to do so by applicable law. In that case, Processor will inform Controller of that legal requirement before Processing, unless the law prohibits such information.</p>
<p>5.2 The Agreement, this DPA, and Controller’s use and configuration of the Services constitute Controller’s complete and final instructions at the time of execution.</p>

<h4>6. Confidentiality</h4>
<p>6.1 Processor will ensure that persons authorized to Process Personal Data have committed themselves to confidentiality or are under an appropriate statutory obligation of confidentiality.</p>
<p>6.2 Processor ensures that such persons are informed of the confidential nature of the Personal Data and have received appropriate training on their responsibilities.</p>

<h4>7. Security of Processing</h4>
<p>7.1 Taking into account the state of the art, the costs of implementation, and the nature, scope, context, and purposes of Processing, as well as the risk to the rights and freedoms of Data Subjects, Processor will implement and maintain appropriate technical and organizational measures to ensure a level of security appropriate to the risk.</p>
<p>7.2 Such measures include, as appropriate:</p>
<ul>
  <li>Encryption of Personal Data in transit and at rest.</li>
  <li>Access controls based on least privilege and role-based access.</li>
  <li>Network security controls, including firewalls and segmentation.</li>
  <li>Logging, monitoring, and intrusion detection.</li>
  <li>Secure software development lifecycle and change management.</li>
  <li>Regular security testing and vulnerability management.</li>
  <li>Business continuity and disaster recovery controls.</li>
</ul>
<p>7.3 Additional details of Processor’s security measures may be set out in a separate Security Policy or technical annex, which forms part of this DPA.</p>

<h4>8. Subprocessors</h4>
<p>8.1 Controller authorizes Processor to engage the subprocessors listed in <strong>Annex 1 (Subprocessors)</strong>, as may be updated from time to time, to Process Personal Data in connection with the Services.</p>
<p>8.2 Processor will enter into written agreements with each Subprocessor that impose data protection obligations no less protective than those set out in this DPA.</p>
<p>8.3 Processor will remain fully liable to Controller for the performance of each Subprocessor’s obligations where that Subprocessor Processes Personal Data on Processor’s behalf.</p>
<p>8.4 Processor will provide Controller with advance notice of any intended addition or replacement of Subprocessors, and Controller may object on reasonable data protection grounds. If the Parties cannot reach a resolution, Controller may terminate the affected Services in accordance with the Agreement.</p>

<h4>9. International Data Transfers</h4>
<p>9.1 Where the Processing of Personal Data involves a transfer to a country outside the European Economic Area, the United Kingdom, or another jurisdiction with adequate protection, Processor will ensure that such transfer complies with applicable data protection laws.</p>
<p>9.2 Where required, the Parties will rely on appropriate safeguards such as:</p>
<ul>
  <li>Standard Contractual Clauses (SCCs) adopted by the European Commission.</li>
  <li>International data transfer agreements or addenda (e.g. UK IDTA).</li>
  <li>Other mechanisms recognized under applicable law.</li>
</ul>
<p>9.3 Processor will make available information on the locations of its data centers and relevant Subprocessors upon request.</p>

<h4>10. Assistance to Controller</h4>
<p>10.1 Taking into account the nature of the Processing and the information available to Processor, Processor will assist Controller in ensuring compliance with its obligations under applicable data protection laws, including with respect to:</p>
<ul>
  <li>Security of Processing.</li>
  <li>Notification of Personal Data breaches to supervisory authorities and Data Subjects.</li>
  <li>Data Protection Impact Assessments (DPIAs) and prior consultations, where required.</li>
</ul>
<p>10.2 Processor will promptly inform Controller if, in its opinion, an instruction infringes applicable data protection laws.</p>

<h4>11. Personal Data Breach Notification</h4>
<p>11.1 Processor will notify Controller without undue delay after becoming aware of a Personal Data Breach affecting Personal Data Processed on behalf of Controller.</p>
<p>11.2 Such notification will include, to the extent reasonably available:</p>
<ul>
  <li>The nature of the breach, including categories and approximate number of Data Subjects and data records concerned.</li>
  <li>The likely consequences of the breach.</li>
  <li>Measures taken or proposed to address the breach and mitigate its possible adverse effects.</li>
</ul>
<p>11.3 Controller is responsible for determining whether to notify any supervisory authority, Data Subjects, or other third parties, as required by law.</p>

<h4>12. Data Subject Rights</h4>
<p>12.1 Processor will, to the extent legally permitted and taking into account the nature of the Processing, assist Controller in responding to requests from Data Subjects to exercise their rights of access, rectification, deletion, restriction, portability, or objection under applicable data protection laws.</p>
<p>12.2 If Processor receives a request directly from a Data Subject relating to Personal Data Processed on behalf of Controller, Processor will promptly forward the request to Controller and will not respond directly unless authorized to do so by Controller or required by law.</p>

<h4>13. Data Retention, Return &amp; Deletion</h4>
<p>13.1 Processor will retain Personal Data only for as long as necessary to provide the Services, fulfill its obligations under the Agreement and this DPA, or as required by law.</p>
<p>13.2 Upon termination or expiry of the Services, Processor will, at Controller’s choice and subject to technical feasibility and legal obligations:</p>
<ul>
  <li>Return all Personal Data to Controller in a commonly used format, and/or</li>
  <li>Delete or anonymize all Personal Data Processed on behalf of Controller, except to the extent that retention is required by law or necessary for the establishment, exercise, or defense of legal claims.</li>
</ul>
<p>13.3 Details on data retention periods and deletion procedures may be described in Processor’s Data Retention Policy, which is incorporated by reference into this DPA.</p>

<h4>14. Audits &amp; Demonstration of Compliance</h4>
<p>14.1 Processor will make available to Controller all information reasonably necessary to demonstrate compliance with the obligations set out in this DPA and applicable data protection laws.</p>
<p>14.2 Processor may provide third-party security certifications, audit reports, or summaries thereof as part of such information.</p>
<p>14.3 Where such documentation does not provide sufficient information, Controller may conduct or mandate an audit, including inspections, of Processor’s facilities and Processing activities, subject to:</p>
<ul>
  <li>Reasonable prior written notice.</li>
  <li>Conduct during normal business hours in a manner that does not unreasonably interfere with Processor’s operations.</li>
  <li>Appropriate confidentiality obligations.</li>
</ul>
<p>14.4 Controller is responsible for any costs associated with audits initiated by Controller, unless an audit reveals a material breach of this DPA attributable to Processor.</p>

<h4>15. Use of Services; Controller Responsibilities</h4>
<p>15.1 Controller is responsible for:</p>
<ul>
  <li>Ensuring that its use of the Services and its instructions to Processor comply with applicable data protection laws.</li>
  <li>Providing all necessary notices and obtaining any required consents from Data Subjects.</li>
  <li>Determining the lawfulness of Processing and the appropriate legal bases.</li>
</ul>
<p>15.2 Controller will not submit or cause to be submitted to the Services any Personal Data that is not necessary for the purposes of the Processing, and will avoid including special categories of data or data relating to children.</p>

<h4>16. Liability &amp; Indemnity</h4>
<p>16.1 The Parties’ liability under this DPA is subject to the limitations and exclusions of liability set out in the Agreement, except to the extent prohibited by applicable law.</p>
<p>16.2 Nothing in this DPA limits either Party’s liability to Data Subjects under applicable data protection laws where such limitation is not permitted.</p>

<h4>17. Term &amp; Termination</h4>
<p>17.1 This DPA enters into force on the effective date of the Agreement or the date on which Processor first Processes Personal Data on behalf of Controller, whichever is earlier.</p>
<p>17.2 This DPA automatically terminates upon deletion of all Personal Data by Processor in accordance with Section 13 or upon termination of the Agreement, whichever is later.</p>
<p>17.3 Provisions of this DPA that by their nature are intended to survive termination (such as confidentiality and liability) will remain in full force and effect.</p>

<h4>18. Governing Law &amp; Jurisdiction</h4>
<p>18.1 This DPA is governed by the same law and jurisdiction as the Agreement, unless otherwise required by applicable data protection laws or specified in the Standard Contractual Clauses or equivalent transfer mechanism.</p>

<h4>19. Order of Precedence</h4>
<p>19.1 In case of conflict between this DPA and the Agreement, this DPA will prevail with respect to the subject matter of data protection and Processing.</p>
<p>19.2 In case of conflict between this DPA and the Standard Contractual Clauses or other mandatory data transfer mechanism, such mechanism will prevail to the extent of the conflict.</p>

