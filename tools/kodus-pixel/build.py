CEDILLA = {'ç': 'c', 'Ç': 'C'}
CEDILLA_MARK = ["..##.", "...##", ".###."]


def parse(art, start=None):
    """Art -> set of (col, row) pixels, rows counted from the cap top.
    start=None means a full-height drawing that begins at the cap top."""
    rows = art.strip('\n').split('\n')
    if start is None:
        start = 0
        assert 14 <= len(rows) <= 18, (len(rows), art)
    return {(c, start + r) for r, line in enumerate(rows) for c, ch in enumerate(line) if ch == '#'}


def trim(pixels):
    """Shift pixels so the leftmost filled column is 0; return (pixels, width)."""
    left = min(c for c, _ in pixels)
    right = max(c for c, _ in pixels)
    return {(c - left, r) for c, r in pixels}, right - left + 1


def mark_pixels(rows, bottom_row, width):
    mw = max(len(r) for r in rows)
    left = (width - mw) // 2
    top = bottom_row - len(rows) + 1
    return {(left + c, top + r) for r, line in enumerate(rows) for c, ch in enumerate(line) if ch == '#'}


def all_glyphs():
    out = {}
    for ch, art in G.items():
        out[ch] = trim(parse(art, ROW_START.get(ch)))
    # dotless i: the i without its dot, base for accented i
    i_px, _ = out['i']
    out['dotlessi'] = trim({(c, r) for c, r in i_px if r >= 4})
    for ch, (base, mark) in ACCENTED.items():
        px, w = out[base]
        lower = min(r for _, r in px) >= 4
        bottom = 2 if lower else -2
        out[ch] = trim(px | mark_pixels(MARKS[mark], bottom, w))
    for ch, base in CEDILLA.items():
        px, w = out[base]
        out[ch] = trim(px | mark_pixels(CEDILLA_MARK, 16, w))
    out['ı'] = out['dotlessi']
    del out['dotlessi']
    return out


def outline(pixels):
    path = pathops.Path()
    for c, r in pixels:
        x0, y0 = (c + SIDE) * PX, (13 - r) * PX
        path.moveTo(x0, y0); path.lineTo(x0 + PX, y0); path.lineTo(x0 + PX, y0 + PX); path.lineTo(x0, y0 + PX); path.close()
    # union so neighbouring pixels share no seams
    path = pathops.simplify(path, fix_winding=True)
    pen = TTGlyphPen(None)
    path.draw(pen)
    return pen.glyph()


def build(out_path):
    glyphs = all_glyphs()
    names = {ch: 'uni%04X' % ord(ch) for ch in glyphs}
    order = ['.notdef', 'space'] + [names[ch] for ch in glyphs]
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    empty = TTGlyphPen(None).glyph()
    glyf = {'.notdef': empty, 'space': empty}
    hmtx = {'.notdef': (8 * PX, 0), 'space': (SPACE * PX, 0)}
    cmap = {0x20: 'space', 0xA0: 'space'}
    for ch, (px, w) in glyphs.items():
        name = names[ch]
        glyf[name] = outline(px)
        hmtx[name] = ((w + 2 * SIDE) * PX, SIDE * PX)
        cmap[ord(ch)] = name
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyf)
    fb.setupHorizontalMetrics(hmtx)
    fb.setupHorizontalHeader(ascent=ASCENT * PX, descent=-DESCENT * PX, lineGap=0)
    fb.setupNameTable({'familyName': 'Kodus Pixel', 'styleName': 'Regular',
                       'copyright': 'Copyright Kodus. Drawn for kodus.io.'})
    fb.setupOS2(version=4, sTypoAscender=ASCENT * PX, sTypoDescender=-DESCENT * PX, sTypoLineGap=0,
                usWinAscent=ASCENT * PX, usWinDescent=DESCENT * PX,
                sCapHeight=14 * PX, sxHeight=10 * PX, fsSelection=0x40 | 0x80)
    fb.setupPost()
    if out_path.endswith('.woff2'):
        fb.font.flavor = 'woff2'
    fb.save(out_path)
    return len(glyphs)


if __name__ == '__main__':
    n = build(sys.argv[1])
    print('built %s (%d glyphs)' % (sys.argv[1], n))
